import { chromium } from 'playwright-core';
import { existsSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
import process from 'node:process';

const executablePath = [process.env.BROWSER_EXECUTABLE_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', chromium.executablePath()].find(p => p && existsSync(p));
const browser = await chromium.launch({ executablePath, headless: true });
const context = await browser.newContext({ viewport: { width: 1586, height: 992 }, colorScheme: 'dark' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
mkdirSync('artifacts/quiet-workspace', { recursive: true });
try {
  await page.goto(process.env.BROWSER_E2E_URL || 'http://127.0.0.1:5173');
  await page.getByRole('button', { name: 'Content', exact: true }).waitFor({ timeout: 5000 });
  assert.equal(await page.getByRole('button', { name: 'Content', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.getByLabel('Native resume file', { exact: true }).setInputFiles({ name: 'design-fixture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ personal: { name: 'Alex Morgan', title: 'Senior Product Designer', email: 'alex.morgan@example.com', location: 'Melbourne, Australia', summary: 'Product designer building thoughtful, accessible digital experiences.' }, sections: [{ id: 'exp', type: 'experience', title: 'Experience', items: [{ id: 'job', role: 'Senior Product Designer', company: 'Northstar', location: 'Melbourne, Australia', start: 'Jan 2022', end: 'Present', bullets: ['Led user research to guide product decisions.', 'Built a reusable design system with engineering partners.'] }] }, { id: 'skills', type: 'skills', title: 'Skills', items: ['User research', 'Figma', 'Prototyping'] }] })) });
  await page.locator('.nav-item').filter({ hasText: 'Experience' }).click();
  await page.getByPlaceholder('Company', { exact: true }).waitFor();
  assert.equal(await page.getByPlaceholder('End', { exact: true }).isDisabled(), true);
  assert.equal(await page.locator('.month-year-field').filter({ has: page.getByPlaceholder('End', { exact: true }) }).locator('.month-year-toggle').count(), 0);
  await page.locator('.entry-heading').click();
  assert.equal(await page.getByPlaceholder('Company', { exact: true }).isVisible(), false);
  await page.locator('.entry-heading').click();
  await page.getByLabel('I currently work here').uncheck();
  assert.equal(await page.getByPlaceholder('End', { exact: true }).isDisabled(), false);
  await page.getByLabel('I currently work here').check();
  await page.waitForFunction(() => document.querySelector('.save-status')?.textContent.trim() === 'Saved on this device');
  await page.screenshot({ path: 'artifacts/quiet-workspace/content.png' });
  const initialZoom = await page.locator('.zoom-value').innerText();
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  assert.notEqual(await page.locator('.zoom-value').innerText(), initialZoom);
  await page.getByRole('button', { name: 'Fit to page', exact: true }).click();
  await page.getByRole('button', { name: 'Expand preview', exact: true }).click();
  await page.locator('.final-preview-pane').waitFor();
  await page.getByRole('button', { name: 'Close expanded preview', exact: true }).click();
  await page.getByRole('button', { name: 'Design', exact: true }).click();
  assert.equal(await page.locator('.nav-item.active').count(), 0);
  await page.locator('.template-card').filter({ has: page.locator('.template-label', { hasText: 'Modern' }) }).click();
  assert.equal(await page.locator('.template-card.active .resume-sheet').count() > 0, true);
  await page.screenshot({ path: 'artifacts/quiet-workspace/design.png' });
  await page.getByRole('button', { name: 'Job Match', exact: true }).click();
  assert.equal(await page.locator('.nav-item.active').count(), 0);
  await page.getByLabel('Job description', { exact: true }).fill('User research, Figma and Kubernetes required.');
  await page.getByLabel('Additional keywords (comma-separated)').fill('user research, Figma');
  await page.getByRole('button', { name: 'Update comparison', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.match-summary')?.textContent.includes('2 of 3'));
  assert.equal((await page.locator('.match-summary').innerText()).includes('%'), false);
  await page.getByRole('button', { name: 'user research', exact: true }).click();
  assert.match(await page.locator('.match-evidence').innerText(), /Led user research/);
  await page.screenshot({ path: 'artifacts/quiet-workspace/job-match.png' });
  await page.locator('.match-evidence').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/quiet-workspace/job-match-evidence.png' });
  await page.getByRole('button', { name: 'Edit Experience', exact: true }).click();
  await page.getByPlaceholder('Company', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Content', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'Job Match', exact: true }).click();
  assert.match(await page.getByLabel('Job description', { exact: true }).inputValue(), /Kubernetes/);
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  assert.equal(await page.getByLabel('Job description', { exact: true }).inputValue(), '');
  await page.getByRole('button', { name: 'My résumés', exact: true }).click();
  await page.getByRole('heading', { name: 'My résumés', exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/quiet-workspace/library.png' });
  await page.getByLabel('Search résumés').fill('not-a-resume');
  assert.equal(await page.locator('.resume-library-card').count(), 0);
  await page.getByLabel('Search résumés').fill('');
  await page.locator('.resume-library-card').first().click();
  await page.getByRole('button', { name: /^History/ }).click();
  await page.getByText('History — saved snapshots', { exact: true }).waitFor();
  await page.locator('.snapshots-popover .popover-close').click();
  await page.locator('.nav-item').filter({ hasText: 'Personal' }).click();
  await page.locator('.document-actions > summary').click();
  await page.getByRole('button', { name: 'Save snapshot', exact: true }).click();
  await page.locator('.document-actions > summary').click();
  await page.getByPlaceholder('Name', { exact: true }).fill('Changed after snapshot');
  await page.getByRole('button', { name: /^History/ }).click();
  await page.getByPlaceholder('Untitled', { exact: true }).fill('Before edits');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('.snapshot-actions').getByRole('button', { name: 'Restore', exact: true }).click();
  assert.equal(await page.getByPlaceholder('Name', { exact: true }).inputValue(), 'Alex Morgan');
  const beforeLibraryImport = await page.evaluate(() => {
    const index = JSON.parse(localStorage.getItem('resume-builder:profiles'));
    return { count: index.profiles.length, id: index.activeProfileId };
  });
  await page.getByRole('button', { name: 'My résumés', exact: true }).click();
  await page.getByLabel('Native resume file', { exact: true }).setInputFiles({ name: 'new.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ personal: { name: 'Another résumé' }, sections: [] })) });
  await page.waitForFunction(() => document.querySelector('.status')?.textContent.startsWith('Imported as new profile'));
  const afterLibraryImport = await page.evaluate(() => JSON.parse(localStorage.getItem('resume-builder:profiles')));
  assert.equal(afterLibraryImport.profiles.length, beforeLibraryImport.count + 1);
  assert.notEqual(afterLibraryImport.activeProfileId, beforeLibraryImport.id);
  assert.equal(await page.evaluate(id => JSON.parse(localStorage.getItem(`resume-builder:profile:${id}`)).personal.name, beforeLibraryImport.id), 'Alex Morgan');
  await page.getByRole('button', { name: 'My résumés', exact: true }).click();
  await page.locator('.resume-library-card').filter({ hasText: 'My Resume' }).click();
  for (const width of [1024, 768, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await page.getByRole('button', { name: 'Content', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `artifacts/quiet-workspace/content-${width}.png` });
  }
  assert.deepEqual(errors, []);
  console.log('PASS: approved shell, navigation, date state, zoom, expansion, real templates, exact evidence, library, history and responsive widths');
} finally { await browser.close(); }
